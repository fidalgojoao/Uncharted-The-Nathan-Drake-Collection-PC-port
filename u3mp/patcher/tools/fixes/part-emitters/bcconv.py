OPMAP={0x00:0x00,0x01:0x02,0x02:0x01,0x04:0x05,0x05:0x06,0x06:0x07,0x07:0x08,0x08:0x09,0x09:0x0a,0x0a:0x0c,0x0f:0x0d,0x10:0x0e,0x11:0x0f,0x12:0x10,0x13:0x11,0x14:0x12,0x15:0x13,0x16:0x14}
def conv(s8,n8,s9,n9):
    out=b''
    for src,n in ((s8,n8),(s9,n9)):
        for i in range(n):
            w=src[4*i:4*i+4]
            if w[0] not in OPMAP: raise ValueError('opcode %#x'%w[0])
            out+=bytes([OPMAP[w[0]]])+w[1:]
    return out
